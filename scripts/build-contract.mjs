/** Ship the patched pre-writer; profile roots do not inherit pnpm patches. */
import { build } from 'esbuild'
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const require = createRequire(import.meta.url)
const source = dirname(require.resolve('dsh-log-contract/package.json'))
const pkg = JSON.parse(readFileSync(join(source, 'package.json'), 'utf8'))
if (pkg.version !== '0.3.17') throw new Error('Review the v4 patch before changing dsh-log-contract versions')
for (const [file, marker] of [
  ['checks.js', 'V4_SURFACE_TYPES'],
  ['checks.js', 'fold(events, projections)'],
  ['prewrite.js', 'input.projections'],
  ['version-support.js', 'Object.freeze([0, 1, 2, 3, 4])'],
]) {
  if (!readFileSync(join(source, 'lib', file), 'utf8').includes(marker)) {
    throw new Error(`Missing v4 patch in ${file}; install dependencies at this workspace root before building`)
  }
}
const license = readFileSync(join(source, 'LICENSE'), 'utf8').replace(/\r\n/g, '\n').trim()
const result = await build({
  absWorkingDir: root,
  stdin: {
    contents: "export { createPreWriter } from './prewrite.js'; export { supportOfLog, TESTED_BASELINE } from './version-support.js';",
    resolveDir: join(source, 'lib'),
    sourcefile: 'retrace-contract-entry.js',
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  external: ['@deepseek-ai/*'],
  write: false,
  metafile: true,
  logLevel: 'silent',
  banner: { js: `/* GENERATED by scripts/build-contract.mjs from dsh-log-contract@0.3.17\n * plus patches/dsh-log-contract@0.3.17.patch. Core host imports stay external.\n\n${license}\n*/` },
})
if (Object.keys(result.metafile.inputs).some((file) => /node_modules[\\/]@deepseek-ai[\\/]/.test(file))) {
  throw new Error('Host runtime code must not be bundled')
}
// pnpm's peer-context directory names are installation-specific, not source.
const code = result.outputFiles[0].text.replace(/^\/\/ .*node_modules\/dsh-log-contract\/lib\//gm, '// dsh-log-contract/lib/').replace(/\r\n/g, '\n')
const outfile = join(root, 'lib', 'vendor', 'dsh-log-contract.js')
if (process.argv.includes('--check')) {
  if (readFileSync(outfile, 'utf8').replace(/\r\n/g, '\n') !== code) throw new Error('Bundled contract is stale; run node scripts/build-contract.mjs')
  console.log('bundled v4 contract: current, host imports external')
} else {
  mkdirSync(dirname(outfile), { recursive: true })
  writeFileSync(outfile, code)
  console.log(`built lib/vendor/dsh-log-contract.js (${Buffer.byteLength(code)} bytes; host imports external)`)
}
